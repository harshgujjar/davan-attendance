C = {'ky': 'ಕ್ಯ', 'gy': 'ಗ್ಯ', 'sh': 'ಶ', 'ch': 'ಚ', 'ts': 'ತ್ಸ', 'ny': 'ನ್ಯ', 'hy': 'ಹ್ಯ', 'by': 'ಬ್ಯ', 'py': 'ಪ್ಯ', 'my': 'ಮ್ಯ', 'ry': 'ರ್ಯ', 'j': 'ಜ',
     'k': 'ಕ', 'g': 'ಗ', 's': 'ಸ', 'z': 'ಜ', 't': 'ತ', 'd': 'ದ', 'n': 'ನ', 'h': 'ಹ', 'f': 'ಫ', 'b': 'ಬ', 'p': 'ಪ', 'm': 'ಮ', 'y': 'ಯ', 'r': 'ರ', 'w': 'ವ', 'v': 'ವ'}
def kan(r):
    out = []
    for word in r.lower().replace("'", " ").replace('!', '').split():
        s, i = word, 0; res = ''
        while i < len(s):
            # syllabic n (before a consonant or at the end)
            if s[i] == 'n' and (i + 1 == len(s) or s[i + 1] not in 'aiueoy'):
                res += 'ನ್' if i + 1 == len(s) else 'ಂ'; i += 1; continue   # final n = ನ್ (ಂ would be read as m)
            # double consonant (small tsu)
            if i + 1 < len(s) and s[i] == s[i + 1] and s[i] not in 'aiueon':
                cc = C.get(s[i], ''); res += cc + '್' if cc else ''; i += 1; continue
            if s.startswith('tch', i): res += 'ತ್'; i += 1; continue
            cons = ''
            for L in (2, 1):
                if s[i:i + L] in C and (L == 2 or s[i] not in 'aiueo'): cons = s[i:i + L]; break
            if cons: i += len(cons)
            vow = ''
            for L in (2, 1):
                if s[i:i + L] in V: vow = s[i:i + L]; break
            if not vow:
                if cons: res += C[cons] + '್'
                else: i += 1
                continue
            i += len(vow)
            res += (C[cons] + V[vow][1]) if cons else V[vow][0]
        out.append(res)
    return ' '.join(out)

